const RANGES = {
  chestCm: { min: 75, max: 135 },
  waistCm: { min: 60, max: 125 },
  hipsCm:  { min: 75, max: 135 },
  bicepCm: { min: 24, max: 48 },
  thighCm: { min: 40, max: 75 },
} as const

function clamp(v: number, min: number, max: number): number {
  return Math.min(max, Math.max(min, v))
}

function lerp(a: number, b: number, t: number): number {
  return a + (b - a) * t
}

function scaleFor(value: number, key: keyof typeof RANGES): number {
  const { min, max } = RANGES[key]
  const t = clamp((value - min) / (max - min), 0, 1)
  return lerp(0.85, 1.15, t)
}

interface Anchor { y: number; scale: number }

// Плавно интерполирует масштаб между опорными высотами; вне диапазона — берёт крайнее значение
function scaleAtY(y: number, anchors: Anchor[]): number {
  if (y <= anchors[0].y) return anchors[0].scale
  for (let i = 0; i < anchors.length - 1; i++) {
    const a = anchors[i], b = anchors[i + 1]
    if (y >= a.y && y <= b.y) {
      const t = (y - a.y) / (b.y - a.y || 1)
      return lerp(a.scale, b.scale, t)
    }
  }
  return anchors[anchors.length - 1].scale
}

function scaleAroundAxis(points: Pt[], axisX: number, anchors: Anchor[]): Pt[] {
  return points.map(([x, y]): Pt => [axisX + (x - axisX) * scaleAtY(y, anchors), y])
}

// Сглаживает открытую (незамкнутую) ломаную квадратичными кривыми через середины отрезков
function smoothOpenPath(points: Pt[]): string {
  if (points.length < 2) return ''
  const mid = (a: Pt, b: Pt): Pt => [(a[0] + b[0]) / 2, (a[1] + b[1]) / 2]
  let d = `M ${points[0][0]},${points[0][1]}`
  for (let i = 1; i < points.length; i++) {
    const p = points[i]
    if (i === points.length - 1) {
      d += ` L ${p[0]},${p[1]}`
    } else {
      const m = mid(p, points[i + 1])
      d += ` Q ${p[0]},${p[1]} ${m[0]},${m[1]}`
    }
  }
  return d
}

export function BodyDiagram() {
  const { measurements } = useMeasurements()
  const latest = useMemo(() => sortByDateAsc(measurements).at(-1), [measurements])

  if (!latest) {
    return (
      <div className="dp-panel overflow-hidden" style={{ width: 153 }}>
        <div className="dp-section-title">Силуэт</div>
        <EmptyCard message="Добавь замер, чтобы увидеть силуэт" />
      </div>
    )
  }

  return <BodyDiagramFigure measurement={latest} />
}

function BodyDiagramFigure({ measurement: m }: { measurement: BodyMeasurement }) {
  const chestScale = scaleFor(m.chestCm, 'chestCm')
  const waistScale = scaleFor(m.waistCm, 'waistCm')
  const hipsScale  = scaleFor(m.hipsCm, 'hipsCm')
  const bicepScale = scaleFor(m.bicepCm, 'bicepCm')
  const thighScale = scaleFor(m.thighCm, 'thighCm')

  const torsoLegAnchors: Anchor[] = [
    { y: 260, scale: 1 },           // подмышка — не замеряется, фиксирована
    { y: 295, scale: chestScale },  // грудь
    { y: 328, scale: waistScale },  // талия (самое узкое место)
    { y: 468, scale: hipsScale },   // бёдра (таз, самое широкое место)
    { y: 495, scale: thighScale },  // бедро (верх ноги)
    { y: 660, scale: 1 },           // колено — не замеряется
    { y: 840, scale: 1 },           // щиколотка/стопа — не замеряется
  ]

  const armAnchors: Anchor[] = [
    { y: 168, scale: 1 },
    { y: 230, scale: 1 },
    { y: 299, scale: bicepScale }, // бицепс — самая широкая точка руки
    { y: 480, scale: 1 },          // кисть — не замеряется
  ]

  const torsoLegLeft  = scaleAroundAxis(LEFT_TORSO_LEG_PTS,  CENTERLINE_X, torsoLegAnchors)
  const torsoLegRight = scaleAroundAxis(RIGHT_TORSO_LEG_PTS, CENTERLINE_X, torsoLegAnchors)
  const armLeft  = scaleAroundAxis(LEFT_ARM_PTS,  LEFT_SHOULDER_AXIS_X,  armAnchors)
  const armRight = scaleAroundAxis(RIGHT_ARM_PTS, RIGHT_SHOULDER_AXIS_X, armAnchors)

  const strokeStyle = { fill: 'none', stroke: 'var(--dp-border-light)', strokeWidth: 1.4, strokeLinejoin: 'round' as const, strokeLinecap: 'round' as const }

  /*
    Точки для выносок ищем как реальный локальный экстремум контура (самая
    выступающая или самая узкая точка) внутри анатомического диапазона
    высот — на уже отмасштабированных точках, так стрелка всегда указывает
    на настоящий видимый изгиб линии.
  */
  function extremumInRange(points: Pt[], yMin: number, yMax: number, dir: 'max' | 'min'): Pt {
    const inRange = points.filter((p) => p[1] >= yMin && p[1] <= yMax)
    const pool = inRange.length > 0 ? inRange : points
    return pool.reduce((best, p) => {
      const better = dir === 'max' ? p[0] > best[0] : p[0] < best[0]
      return better ? p : best
    })
  }

  // Слева (LEFT_*) контур смещён левее централи — там "шире" значит меньший X.
  const chestPt = extremumInRange(torsoLegLeft, 270, 330, 'min')
  const waistPt = extremumInRange(torsoLegLeft, 300, 360, 'max')
  const thighPt = extremumInRange(torsoLegLeft, 470, 560, 'min')
  // Справа (RIGHT_*) контур смещён правее централи — там "шире" значит больший X.
  const hipsPt  = extremumInRange(torsoLegRight, 400, 470, 'max')
  const bicepPt = extremumInRange(armRight, 150, 320, 'max')

  return (
    <div className="dp-panel overflow-hidden" style={{ width: 153 }}>
      <div className="dp-section-title">Силуэт</div>

      <div className="p-2">
        <svg viewBox="0 0 390 878" width="100%" style={{ display: 'block', overflow: 'visible' }}>
          <path d={smoothOpenPath(HEAD_R_PTS)} style={strokeStyle} />
          <path d={smoothOpenPath(HEAD_L_PTS)} style={strokeStyle} />
          <path d={smoothOpenPath(armLeft)} style={strokeStyle} />
          <path d={smoothOpenPath(armRight)} style={strokeStyle} />
          <path d={smoothOpenPath(torsoLegLeft)} style={strokeStyle} />
          <path d={smoothOpenPath(torsoLegRight)} style={strokeStyle} />

          {/* ── Подписи-выноски ── */}
          <Callout label="Грудь" value={`${m.chestCm} см`} x1={18} y1={chestPt[1] - 8} x2={chestPt[0]} y2={chestPt[1]} align="left" />
          <Callout label="Талия" value={`${m.waistCm} см`} x1={18} y1={waistPt[1]} x2={waistPt[0]} y2={waistPt[1]} align="left" />
          <Callout label="Бедро" value={`${m.thighCm} см`} x1={18} y1={thighPt[1]} x2={thighPt[0]} y2={thighPt[1]} align="left" />

          <Callout label="Бицепс" value={`${m.bicepCm} см`} x1={372} y1={bicepPt[1]} x2={bicepPt[0]} y2={bicepPt[1]} align="right" />
          <Callout label="Бёдра" value={`${m.hipsCm} см`} x1={372} y1={hipsPt[1] - 8} x2={hipsPt[0]} y2={hipsPt[1]} align="right" />
        </svg>
      </div>

      <div
        className="flex items-center justify-center gap-1.5 pb-3 text-xs"
        style={{ color: 'var(--dp-text-secondary)' }}
      >
        ⚖ Вес <span className="font-mono" style={{ color: 'var(--dp-text-primary)' }}>{m.weightKg} кг</span>
      </div>
    </div>
  )
}

